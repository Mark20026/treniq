// ==================== I18N RENDSZER ====================
const translations = { hu, sk, en };

export type Language = 'hu' | 'sk' | 'en';

let currentLanguage: Language = 'hu';
let listeners: Array<(lang: Language) => void> = [];

const getNestedValue = (obj: any, path: string): any => {
  if (!obj || !path) return undefined;
  return path.split('.').reduce((acc, part) => acc && acc[part], obj);
};

export const t = (key: string, data?: { count?: number; date?: string }): string => {
  const keys = key.split(':');
  const namespace = keys[0];
  const translationKey = keys[1];

  if (!translationKey) return key;
  let result = key;

  try {
    const ns = translations[currentLanguage][namespace as keyof typeof hu];
    const val = getNestedValue(ns, translationKey);
    if (typeof val === 'string') result = val;
  } catch (error) {
    try {
      const ns = translations.hu[namespace as keyof typeof hu];
      const val = getNestedValue(ns, translationKey);
      if (typeof val === 'string') result = val;
    } catch (err) {}
  }

  if (data) {
    if (data.count !== undefined) {
      result = result.replace("{{count}}", data.count.toString());
    }
    if (data.date !== undefined) {
      result = result.replace("{{date}}", data.date);
    }
  }

  return result;
};

export const changeLanguage = async (lang: Language) => {
  currentLanguage = lang;
  await AsyncStorage.setItem('app-language', lang);
  listeners.forEach(listener => listener(lang));
};

export const getStoredLanguage = async (): Promise<Language> => {
  try {
    const lang = await AsyncStorage.getItem('app-language');
    if (lang === 'hu' || lang === 'sk' || lang === 'en') return lang;
  } catch (error) {}
  return 'hu';
};

export const getCurrentLanguage = (): Language => {
  return currentLanguage;
};

export const subscribeToLanguageChange = (callback: (lang: Language) => void) => {
  listeners.push(callback);
  return () => {
    listeners = listeners.filter(listener => listener !== callback);
  };
};

// Inicializálás
getStoredLanguage().then(lang => {
  currentLanguage = lang;
});

export default { t, changeLanguage, getStoredLanguage, getCurrentLanguage, subscribeToLanguageChange };
